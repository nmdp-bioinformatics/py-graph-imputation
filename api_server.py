#!/usr/bin/env python3
"""
API Server for HLA imputation with dynamic configuration loading.
Uses the configuration generated by the Streamlit UI.
"""

import json
import argparse
from pathlib import Path
from flask import Flask, request, jsonify
from flask_cors import CORS

app = Flask(__name__)
CORS(app)

# Global config
current_config = {}
BASE_DIR = Path(__file__).parent


class InvalidAllele(Exception):
    """Exception for invalid allele data."""

    def __init__(self, message):
        self.message = message
        super().__init__(message)


def load_config(config_file):
    """Load configuration from JSON file."""
    global current_config

    config_path = Path(config_file)

    # If path doesn't exist and is relative, try conf/ directory
    if not config_path.exists() and not config_file.startswith("/"):
        alt_path = BASE_DIR / "conf" / config_file
        if alt_path.exists():
            config_path = alt_path

    if not config_path.exists():
        raise FileNotFoundError(f"Configuration file not found: {config_path}")

    with open(config_path) as f:
        current_config = json.load(f)

    print(f"✅ Configuration loaded from: {config_path}")
    print(f"   Populations: {current_config.get('populations', [])}")
    print(f"   Number of results: {current_config.get('number_of_results', 'N/A')}")
    return current_config


@app.route("/health", methods=["GET"])
def health_check():
    """Health check endpoint."""
    return (
        jsonify(
            {
                "status": "healthy",
                "config_loaded": bool(current_config),
                "populations": current_config.get("populations", []),
            }
        ),
        200,
    )


@app.route("/config", methods=["GET"])
def get_config():
    """Get current configuration."""
    if not current_config:
        return jsonify({"error": "No configuration loaded"}), 500
    return jsonify(current_config), 200


@app.route("/impute", methods=["POST"])
def impute():
    """
    Imputation endpoint - accepts patient and donor HLA strings.
    Expected JSON: {"patient": "...", "donor": "..."}

    Currently returns a mock response with configuration info.
    When fully integrated with grim.grim.match, this will perform actual imputation.
    """
    if not current_config:
        return jsonify({"error": "No configuration loaded"}), 500

    if not request.json:
        return jsonify({"message": "No input provided"}), 404

    try:
        patient_slug = request.json.get("patient")
        donor_slug = request.json.get("donor")

        if not patient_slug or not donor_slug:
            return (
                jsonify({"message": "Invalid data - both patient and donor required"}),
                400,
            )

        # TODO: When grim.grim.match is integrated, replace this with:
        # donor_result, matched, patient_result = match(patient_slug, donor_slug)

        return (
            jsonify(
                {
                    "matched": "Match",
                    "patient": str(patient_slug),
                    "donor": str(donor_slug),
                    "config": {
                        "populations": current_config.get("populations", []),
                        "epsilon": current_config.get("epsilon"),
                        "number_of_results": current_config.get("number_of_results"),
                    },
                    "note": "Mock response - full imputation not yet integrated",
                }
            ),
            200,
        )

    except InvalidAllele as e:
        return jsonify({"message": str(e.message)}), 400
    except Exception as e:
        return jsonify({"message": f"Error: {str(e)}"}), 500


@app.route("/match", methods=["POST"])
def slug_match_controller():
    """
    Legacy endpoint for slug matching (for compatibility).
    Expected JSON: {"patient_slug": "...", "donor_slug": "..."}

    Currently returns a mock response with configuration info.
    """
    if request.json:
        try:
            patient_slug_glstring = request.json.get("patient_slug")
            donor_slug_glstring = request.json.get("donor_slug")

            if not patient_slug_glstring or not donor_slug_glstring:
                return (
                    jsonify({"message": "Invalid data in patient_slug/donor_slug"}),
                    400,
                )

            # TODO: When grim.grim.match is integrated, replace this with:
            # donor_slug, matched, patient_slug = match(patient_slug_glstring, donor_slug_glstring)

            return (
                jsonify(
                    {
                        "matched": "Match",
                        "patient_slug": str(patient_slug_glstring),
                        "donor_slug": str(donor_slug_glstring),
                        "config_applied": current_config.get("populations", []),
                        "note": "Mock response - full imputation not yet integrated",
                    }
                ),
                200,
            )

        except InvalidAllele as e:
            return jsonify({"message": e.message}), 400

    return jsonify({"message": "No input provided"}), 404


@app.route("/", methods=["GET"])
def index():
    """Root endpoint with API documentation."""
    return (
        jsonify(
            {
                "name": "HLA Imputation API",
                "version": "1.0.0",
                "endpoints": {
                    "/health": "GET - Health check",
                    "/config": "GET - Get current configuration",
                    "/impute": "POST - Perform imputation",
                    "/match": "POST - Legacy match endpoint",
                },
                "config_loaded": bool(current_config),
            }
        ),
        200,
    )


def main():
    parser = argparse.ArgumentParser(description="HLA Imputation API Server")
    parser.add_argument(
        "--config",
        required=True,
        help="Configuration file name (in conf/) or full path",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=5000,
        help="Port to run the server on (default: 5000)",
    )
    parser.add_argument("--debug", action="store_true", help="Run in debug mode")

    args = parser.parse_args()

    try:
        load_config(args.config)
        print(f"\n🚀 Starting HLA Imputation API Server")
        print(f"   Port: {args.port}")
        print(f"   Debug: {args.debug}")
        app.run(host="0.0.0.0", port=args.port, debug=args.debug)
    except FileNotFoundError as e:
        print(f"❌ Error: {e}")
        exit(1)


if __name__ == "__main__":
    main()
